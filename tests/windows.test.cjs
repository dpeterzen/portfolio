const assert = require('node:assert/strict');
const DesktopState = require('../dist/window-state.js');
const state = new DesktopState(['about','tiles','paintings','guestbook']);
state.open('about'); state.open('tiles'); state.open('paintings');
assert.equal(state.active,'paintings');
assert.ok(state.get('paintings').z>state.get('tiles').z);
state.minimize('paintings');
assert.equal(state.active,'tiles'); assert.equal(state.get('paintings').open,true);
state.task('paintings'); assert.equal(state.active,'paintings'); assert.equal(state.get('paintings').minimized,false);
state.task('paintings'); assert.equal(state.get('paintings').minimized,true); assert.equal(state.active,'tiles');
state.maximize('tiles'); assert.equal(state.get('tiles').maximized,true);
state.minimize('tiles'); state.open('tiles'); assert.equal(state.get('tiles').maximized,true,'task restore retains maximized state');
state.maximize('tiles'); assert.equal(state.get('tiles').maximized,false);
state.desktop(); assert.equal(state.active,null); assert.equal(state.get('about').minimized,true);
state.desktop(); assert.equal(state.active,'tiles'); assert.equal(state.get('about').minimized,false); assert.equal(state.get('paintings').minimized,true,'already-minimized windows stay minimized');
state.desktop(); state.close('about'); state.desktop();
assert.equal(state.get('about').open,false,'show-desktop restore never reopens closed windows'); assert.equal(state.active,'tiles');
state.close('tiles'); assert.equal(state.active,null);
state.open('guestbook');state.desktop();state.open('paintings');state.desktop();state.desktop();
assert.equal(state.active,'paintings');assert.equal(state.get('guestbook').minimized,true,'opening a new window starts a new desktop group');
state.close('paintings');state.open('paintings');assert.equal(state.active,'paintings');assert.equal(state.get('paintings').open,true);
assert.throws(()=>state.open('missing'),/Unknown window/);
console.log('PASS: focus stacking, taskbar minimize/restore, maximize restoration, closed windows, show desktop groups, and independent window state.');
